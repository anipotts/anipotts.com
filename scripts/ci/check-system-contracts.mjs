import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const generated = join(root, "apps/admin/src/lib/generated");

function select(schema, pointer) {
  if (!pointer.startsWith("/")) throw new Error("invalid contract selector");
  return pointer
    .slice(1)
    .split("/")
    .reduce(
      (value, key) => value[key.replaceAll("~1", "/").replaceAll("~0", "~")],
      schema,
    );
}

export function checkSystemContracts(directory = generated) {
  const errors = [];
  const expectedContracts = {
    "personal-context-source.json": "personal-context.sources",
    "private-reader.json": "system.private-reader",
    "ops.json": "system.ops",
  };
  const manifests = readdirSync(directory).filter((name) =>
    name.endsWith(".json"),
  );
  for (const name of Object.keys(expectedContracts)) {
    if (!manifests.includes(name))
      errors.push(`${name}: required System contract missing`);
  }
  for (const name of manifests) {
    try {
      const manifest = JSON.parse(readFileSync(join(directory, name), "utf8"));
      const raw = Buffer.from(manifest.source_text);
      const sha256 = createHash("sha256").update(raw).digest("hex");
      const blob = createHash("sha1")
        .update(`blob ${raw.length}\0`)
        .update(raw)
        .digest("hex");
      if (
        manifest.source.owner !== "system" ||
        manifest.source.contract_version !== "1" ||
        manifest.source.contract !== expectedContracts[name] ||
        manifest.source.definition !==
          `contracts/${name.replace(/\.json$/, ".schema.json")}` ||
        sha256 !== manifest.source.sha256 ||
        `git-blob:${blob}` !== manifest.source.source_revision ||
        JSON.stringify(JSON.parse(manifest.source_text)) !==
          JSON.stringify(manifest.schema)
      ) {
        throw new Error("invalid source pin");
      }
      const exports = {};
      for (const [key, pointer] of Object.entries(manifest.selectors)) {
        if (!/^[A-Z][A-Z0-9_]*$/.test(key))
          throw new Error("invalid export name");
        exports[key] = select(manifest.schema, pointer);
      }
      if (JSON.stringify(exports) !== JSON.stringify(manifest.exports))
        throw new Error("stale exports");
      let expectedText =
        "// generated by System/bin/contracts-generate; edit the owner definition.\n";
      for (const [key, value] of Object.entries({
        CONTRACT_SOURCE: manifest.source,
        ...exports,
      })) {
        expectedText += `export const ${key} = ${JSON.stringify(value, null, 2)} as const;\n`;
      }
      if (
        readFileSync(
          join(directory, name.replace(/\.json$/, ".ts")),
          "utf8",
        ) !== expectedText
      ) {
        throw new Error("stale adapter");
      }
    } catch {
      errors.push(`${name}: pinned System contract or generated adapter drift`);
    }
  }
  return errors;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const errors = checkSystemContracts();
  if (errors.length) {
    for (const error of errors) console.error(error);
    process.exitCode = 1;
  } else console.log("pinned System contracts and adapters agree");
}
